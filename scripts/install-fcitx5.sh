#!/bin/sh
set -eu

die() {
    printf 'install-fcitx5: %s\n' "$*" >&2
    exit 1
}

install_packages() {
    chinese=$1
    . "${ROOTFS_DIR:-}/etc/os-release"
    case "$ID" in
        debian|ubuntu)
            set -- apt-get install -y --no-install-recommends fcitx5 fcitx5-config-qt \
                fcitx5-frontend-gtk2 fcitx5-frontend-gtk3 fcitx5-frontend-gtk4 \
                fcitx5-frontend-qt5 fcitx5-frontend-qt6
            ;;
        fedora)
            set -- dnf install -y --setopt=install_weak_deps=False fcitx5 fcitx5-configtool \
                fcitx5-gtk2 fcitx5-gtk3 fcitx5-gtk4 fcitx5-qt5 fcitx5-qt6
            ;;
        arch|archarm|archlinux)
            set -- pacman -S --noconfirm --needed fcitx5-im
            ;;
        *) die "unsupported distribution: $ID" ;;
    esac
    if [ "$chinese" = true ]; then
        set -- "$@" fcitx5-chinese-addons
    fi
    "$@"
}

append_config() {
    if ! grep -Fqx -- "$2" "$1"; then
        printf '\n%s\n' "$2" >> "$1"
    fi
}

set_ini_default() {
    ini_file=$1
    install -d -m 0755 "$(dirname "$ini_file")"
    touch "$ini_file"
    ini_tmp=$(mktemp)
    if awk -v section="[$2]" -v key="$3" -v value="$4" '
        $0 == section { in_section = found = 1 }
        /^\[/ && $0 != section && in_section { write_default(); in_section = 0 }
        in_section && $0 ~ "^[[:space:]]*" key "([[:space:]]|\\[|=)" { written = 1 }
        { print }
        END {
            if (!found) print section
            write_default()
        }
        function write_default() {
            if (!written) print key "=" value
            written = 1
        }
    ' "$ini_file" > "$ini_tmp"; then
        cat "$ini_tmp" > "$ini_file"
    else
        rm -f "$ini_tmp"
        die "could not read $ini_file"
    fi
    rm -f "$ini_tmp"
}

add_compositor_startup() {
    user_config=$config/$1
    default_config=$2
    startup=$3
    if [ ! -f "$user_config" ]; then
        install -Dm0644 "$rootfs$default_config" "$user_config"
    fi
    append_config "$user_config" "$startup"
}

configure_session() {
    desktop=$1 backend=$2 username=$3 chinese=$4
    rootfs=${ROOTFS_DIR:-}
    if [ -n "$rootfs" ]; then
        home=$rootfs/home/$username
    else
        home=$(getent passwd "$username" | cut -d: -f6)
    fi
    [ -n "$home" ] && [ -d "$home" ] || die "home directory not found for $username"
    config=$home/.config
    autostart=$config/autostart/org.fcitx.Fcitx5.desktop
    libdir=$rootfs/usr/local/lib/droidspaces
    install -d -m 0755 "$config/autostart"

    # Desktop packages may already have installed im-config on Debian/Ubuntu.
    if [ -x "$rootfs/usr/bin/im-config" ] && [ ! -e "$home/.xinputrc" ]; then
        printf '%s\n' 'run_im none' > "$home/.xinputrc"
    fi

    # Remove the launch entry generated by earlier RootFS builds if it matches.
    legacy_autostart=$config/autostart/fcitx5.desktop
    if [ -f "$legacy_autostart" ] && grep -Fxq 'Exec=fcitx5 -d' "$legacy_autostart" &&
        grep -Fxq 'Comment=Start Input Method' "$legacy_autostart"; then
        rm -f "$legacy_autostart"
    fi

    environment=$rootfs/etc/environment
    touch "$environment"
    sed -Ei '/^# BEGIN droidspaces-fcitx5$/,/^# END droidspaces-fcitx5$/d
        /^(XMODIFIERS=@im=fcitx5|GTK_IM_MODULE=fcitx5|QT_IM_MODULE=fcitx5|SDL_IM_MODULE=fcitx5|GLFW_IM_MODULE=fcitx)$/d' "$environment"
    if [ "$backend" = anland-wayland ]; then
        sed -i 's/^QT_QPA_PLATFORM=wayland$/QT_QPA_PLATFORM="wayland;xcb"/' "$environment"
    fi
    {
        printf '%s\n' '# BEGIN droidspaces-fcitx5' 'XMODIFIERS=@im=fcitx' 'QT_IM_MODULE=fcitx'
        case "$backend:$desktop" in
            x11:*) printf '%s\n' 'GTK_IM_MODULE=fcitx' 'SDL_IM_MODULE=fcitx' ;;
            # Anland Next's bridge has no external input-method protocol.
            anland-wayland:anland-next) printf '%s\n' 'GTK_IM_MODULE=fcitx' ;;
            *) printf '%s\n' 'QT_IM_MODULES="wayland;fcitx"' ;;
        esac
        printf '%s\n' '# END droidspaces-fcitx5'
    } >> "$environment"

    launch='/usr/bin/fcitx5 -d --replace'
    autostart_command=$launch
    if [ "$backend" = anland-wayland ]; then
        # GTK uses these settings on X11 and prefers text-input on Wayland.
        touch "$home/.gtkrc-2.0"
        if ! grep -Eq '^[[:space:]]*gtk-im-module[[:space:]]*=' "$home/.gtkrc-2.0"; then
            append_config "$home/.gtkrc-2.0" 'gtk-im-module="fcitx"'
        fi
        set_ini_default "$config/gtk-3.0/settings.ini" Settings gtk-im-module fcitx
        set_ini_default "$config/gtk-4.0/settings.ini" Settings gtk-im-module fcitx

        case "$desktop" in
            kde|kde-mobile)
                set_ini_default "$config/kwinrc" Wayland InputMethod /usr/share/applications/org.fcitx.Fcitx5.desktop
                set_ini_default "$config/kwinrc" Wayland VirtualKeyboardEnabled true
                # KWin starts Fcitx5 with its input-method socket. Attach XIM
                # using the live DISPLAY once Plasma runs its autostart entries.
                install -d -m 0755 "$libdir"
                cat > "$libdir/fcitx5-xwayland" <<'EOF'
#!/bin/sh
[ -n "${DISPLAY:-}" ] || exit 0
attempts=0
until /usr/bin/fcitx5-remote --check >/dev/null 2>&1; do
    [ "$attempts" -lt 20 ] || exit 0
    attempts=$((attempts + 1))
    sleep 0.25
done
# KWin may already have passed DISPLAY to Fcitx5.
/usr/bin/fcitx5-remote --check -x 2>/dev/null || :
EOF
                chmod 0755 "$libdir/fcitx5-xwayland"
                autostart_command=/usr/local/lib/droidspaces/fcitx5-xwayland
                ;;
            gnome)
                # GNOME's XSettings value has higher priority than settings.ini.
                schemas=$rootfs/usr/share/glib-2.0/schemas
                cat > "$schemas/90-droidspaces-fcitx5.gschema.override" <<'EOF'
[org.gnome.desktop.interface]
gtk-im-module='fcitx'
EOF
                glib-compile-schemas "$schemas"
                ;;
            niri)
                defaults=/etc/niri/config.kdl
                [ -f "$rootfs$defaults" ] || defaults=/usr/share/doc/niri-anland/default-config.kdl
                add_compositor_startup niri/config.kdl "$defaults" 'spawn-at-startup "/usr/bin/fcitx5" "-d" "--replace"'
                autostart_command=
                ;;
            hyprland)
                defaults=
                for share in /usr/share/hypr /usr/lib64/hyprland-anland/share/hypr /usr/lib/hyprland-anland/share/hypr; do
                    if [ -f "$config/hypr/hyprland.lua" ] || [ -f "$rootfs$share/hyprland.lua" ]; then
                        defaults=$share/hyprland.lua
                    elif [ -f "$config/hypr/hyprland.conf" ] || [ -f "$rootfs$share/hyprland.conf" ]; then
                        defaults=$share/hyprland.conf
                    fi
                    [ -z "$defaults" ] || break
                done
                case "$defaults" in
                    *.lua) add_compositor_startup hypr/hyprland.lua "$defaults" \
                        'hl.on("hyprland.start", function() hl.exec_cmd("/usr/bin/fcitx5 -d --replace") end)' ;;
                    *.conf) add_compositor_startup hypr/hyprland.conf "$defaults" "exec-once = $launch" ;;
                    *) die 'Hyprland configuration template not found' ;;
                esac
                autostart_command=
                ;;
            mango)
                add_compositor_startup mango/config.conf /etc/mango-anland/config.conf "exec_once=$launch"
                autostart_command=
                ;;
            denial)
                units=$rootfs/etc/systemd/user
                install -d -m 0755 "$units/denial-session.target.wants"
                cat > "$units/droidspaces-fcitx5.service" <<'EOF'
[Unit]
Description=Fcitx 5 input method
PartOf=denial-session.target

[Service]
ExecStart=/usr/bin/fcitx5 --replace
EOF
                ln -sfn ../droidspaces-fcitx5.service "$units/denial-session.target.wants/droidspaces-fcitx5.service"
                autostart_command=
                ;;
            anland-next)
                # anland-session invokes mini-wm after publishing both displays.
                install -d -m 0755 "$libdir"
                cat > "$libdir/fcitx5-anland-miniwm" <<'EOF'
#!/bin/sh
/usr/bin/fcitx5 -d --replace
exec /usr/bin/anland-miniwm "$@"
EOF
                chmod 0755 "$libdir/fcitx5-anland-miniwm"
                touch "$config/anlandx.env"
                append_config "$config/anlandx.env" ': "${ANLAND_MINIWM:=/usr/local/lib/droidspaces/fcitx5-anland-miniwm}"'
                autostart_command=
                ;;
        esac
    fi

    # Use the packaged entry's name to avoid starting two instances.
    {
        printf '%s\n' '[Desktop Entry]' 'Type=Application' 'Name=Fcitx 5' 'NoDisplay=true'
        if [ -n "$autostart_command" ]; then
            printf 'Exec=%s\n' "$autostart_command"
        else
            printf '%s\n' 'Exec=/usr/bin/fcitx5' 'Hidden=true'
        fi
    } > "$autostart"

    if [ "$chinese" = true ] && [ ! -e "$config/fcitx5/profile" ]; then
        install -d -m 0755 "$config/fcitx5"
        cat > "$config/fcitx5/profile" <<'EOF'
[Groups/0]
Name=Default
Default Layout=us
DefaultIM=pinyin

[Groups/0/Items/0]
Name=keyboard-us

[Groups/0/Items/1]
Name=pinyin

[GroupOrder]
0=Default
EOF
    fi
}

case "${1:-}" in
    install)
        [ "$#" -eq 2 ] || die 'usage: install-fcitx5 install CHINESE'
        install_packages "$2"
        ;;
    configure)
        [ "$#" -eq 5 ] || die 'usage: install-fcitx5 configure DESKTOP BACKEND USER CHINESE'
        case "$3" in x11|anland-wayland) ;; *) die "unsupported display backend: $3" ;; esac
        configure_session "$2" "$3" "$4" "$5"
        ;;
    *) die 'expected install or configure' ;;
esac
